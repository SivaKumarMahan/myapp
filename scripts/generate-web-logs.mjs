/**
 * Writes src/content/sql/datasets/logs.sql: 400 web-server log lines over
 * three days, from a seeded generator so the file (and every challenge's
 * expected result) is reproducible. Run with `node scripts/generate-web-logs.mjs`.
 */
import { writeFileSync } from 'node:fs'

let seed = 20251001
const random = () => {
  // Park-Miller minimal standard generator: deterministic across platforms.
  seed = (seed * 16807) % 2147483647
  return seed / 2147483647
}
const pick = (items) => items[Math.floor(random() * items.length)]
const weighted = (pairs) => {
  const total = pairs.reduce((sum, [, weight]) => sum + weight, 0)
  let roll = random() * total
  for (const [value, weight] of pairs) {
    roll -= weight
    if (roll <= 0) return value
  }
  return pairs[pairs.length - 1][0]
}

const paths = [
  ['/', 30, 80],
  ['/products', 20, 140],
  ['/products/42', 12, 160],
  ['/cart', 10, 210],
  ['/checkout', 6, 650],
  ['/api/search', 14, 420],
  ['/api/recommendations', 6, 900],
  ['/login', 8, 120],
  ['/health', 10, 5],
]
const ips = Array.from({ length: 18 }, (_, i) => `10.0.${Math.floor(i / 6)}.${10 + i}`)
const agents = [
  'Mozilla/5.0 (Windows NT 10.0)',
  'Mozilla/5.0 (Macintosh)',
  'Mozilla/5.0 (iPhone)',
  'curl/8.5.0',
  'Googlebot/2.1',
]

const start = Date.UTC(2025, 9, 1, 0, 0, 0)
const rows = []
for (let id = 1; id <= 400; id += 1) {
  const ts = new Date(start + Math.floor(random() * 3 * 86_400_000))
  const [path, , baseMs] = weighted(paths.map((entry) => [entry, entry[1]]))
  const method =
    path.startsWith('/api') || path === '/checkout'
      ? weighted([
          ['POST', 3],
          ['GET', 2],
        ])
      : 'GET'
  // One noisy client and a slow recommendations service make the error and
  // latency questions have a clear answer.
  const ip = random() < 0.12 ? '10.0.9.99' : pick(ips)
  let status = weighted([
    [200, 80],
    [301, 4],
    [404, 6],
    [500, 3],
    [503, 2],
  ])
  if (ip === '10.0.9.99' && random() < 0.5) status = pick([401, 403, 500])
  if (path === '/api/recommendations' && random() < 0.25) status = 503
  const responseMs = Math.round(baseMs * (0.5 + random()) + (status >= 500 ? 400 : 0))
  const bytes = status === 301 ? 0 : Math.round(500 + random() * 40_000)
  rows.push([
    id,
    ts.toISOString().slice(0, 19).replace('T', ' '),
    ip,
    method,
    path,
    status,
    bytes,
    responseMs,
    pick(agents),
  ])
}
rows.sort((a, b) => a[1].localeCompare(b[1]))
rows.forEach((row, index) => (row[0] = index + 1))

const quote = (value) =>
  typeof value === 'number' ? String(value) : `'${value.replace(/'/g, "''")}'`
const sql = `-- Web logs: ${rows.length} requests over three days (UTC), generated by
-- scripts/generate-web-logs.mjs. ts is 'YYYY-MM-DD HH:MM:SS', so SQLite's
-- date functions (strftime, date) work on it directly.

CREATE TABLE web_logs (
  id INTEGER PRIMARY KEY,
  ts TEXT NOT NULL,
  ip TEXT NOT NULL,
  method TEXT NOT NULL,
  path TEXT NOT NULL,
  status INTEGER NOT NULL,
  bytes INTEGER NOT NULL,
  response_ms INTEGER NOT NULL,
  user_agent TEXT NOT NULL
);

INSERT INTO web_logs (id, ts, ip, method, path, status, bytes, response_ms, user_agent) VALUES
${rows.map((row) => `  (${row.map(quote).join(', ')})`).join(',\n')};
`
writeFileSync(new URL('../src/content/sql/datasets/logs.sql', import.meta.url), sql)
console.log(`wrote ${rows.length} rows`)
