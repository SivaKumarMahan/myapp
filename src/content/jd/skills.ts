/**
 * The skills a job description can ask for, and the words JDs use for them.
 *
 * `aliases` are matched as whole words, ignoring case, against the job
 * description and against every interview question. An alias starting with
 * `=` is matched case-sensitively, for short words that are also ordinary
 * English ("Go", "DR", "ADO"). `topics` are interview topic ids whose
 * questions rank first and get an "Open topic" link.
 *
 * To teach the JD scanner a new skill, add an entry here. A skill with no
 * matching questions is shown as "not in the app yet" with web search links.
 */

